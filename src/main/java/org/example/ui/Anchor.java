package org.example.ui;

/**
 * Точка привязки виджета к экрану (anchoring, как в Minecraft HUD).
 *
 * Каждый вариант описывает, как из (offsetX, offsetY) высчитать
 * координаты x, y с учётом ширины/высоты виджета и размеров экрана.
 *
 * Например:
 *   Anchor.BOTTOM_CENTER + offset(0, 8) -> виджет прижат к низу, по центру,
 *                                          с отступом 8px от нижнего края.
 *
 *   Anchor.DRAG -> координаты НЕ пересчитываются автоматически.
 *                  x/y задаются вручную (или меняются драгом окна).
 *                  Используется для окон инвентаря/сундука.
 */
public enum Anchor {

    /** Верхний левый угол: (offsetX, offsetY). */
    TOP_LEFT,

    /** Верхний центр: (вдоль центра по X, offsetY от верха). */
    TOP_CENTER,

    /** Верхний правый угол: (offsetX от правого края, offsetY от верха). */
    TOP_RIGHT,

    /** Центр экрана: ((screenW-w)/2+offsetX, (screenH-h)/2+offsetY). */
    CENTER,

    /** Нижний левый угол: (offsetX, offsetY от нижнего края). */
    BOTTOM_LEFT,

    /** Низ по центру: (по центру X, offsetY от нижнего края). */
    BOTTOM_CENTER,

    /** Нижний правый угол: (offsetX от правого, offsetY от нижнего края). */
    BOTTOM_RIGHT,

    /** Свободные/ручные координаты: x, y НЕ трогаем (окна, драг-панели). */
    DRAG
}
